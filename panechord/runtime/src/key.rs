#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn common_codes_are_typed_and_unknown_native_names_do_not_escape() {
        assert_eq!(KeyCode::from_name("KeyV"), KeyCode::KeyV);
        assert_eq!(KeyCode::from_name("MetaLeft"), KeyCode::SuperLeft);
        assert_eq!(KeyCode::from_name("F11").as_str(), "F11");
        assert_eq!(
            KeyCode::from_name("NativeUnknown(42)"),
            KeyCode::Unidentified
        );
    }
}
