macro_rules! key_codes {
    ($($code:ident),+ $(,)?) => {
        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
        pub enum KeyCode { #[default] Unidentified, $($code),+ }
        impl KeyCode {
            pub fn from_name(name: &str) -> Self {
                match name { $(stringify!($code) => Self::$code,)+ "MetaLeft" => Self::SuperLeft, "MetaRight" => Self::SuperRight, _ => Self::Unidentified }
            }
            pub fn as_str(self) -> &'static str {
                match self { Self::Unidentified => "Unidentified", $(Self::$code => stringify!($code),)+ }
            }
        }
    };
}
