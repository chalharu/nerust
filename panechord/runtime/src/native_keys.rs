pub fn windows_set1(code: u32) -> KeyCode {
    use KeyCode::*;
    match code {
        0xe01c => NumpadEnter,
        0xe01d => ControlRight,
        0xe035 => NumpadDivide,
        0xe037 => PrintScreen,
        0xe038 => AltRight,
        0xe047 => Home,
        0xe048 => ArrowUp,
        0xe049 => PageUp,
        0xe04b => ArrowLeft,
        0xe04d => ArrowRight,
        0xe04f => End,
        0xe050 => ArrowDown,
        0xe051 => PageDown,
        0xe052 => Insert,
        0xe053 => Delete,
        0xe05b => SuperLeft,
        0xe05c => SuperRight,
        0xe05d => ContextMenu,
        0xe11d => Pause,
        value if value <= 88 => evdev(value),
        _ => Unidentified,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn native_codes_from_all_hosts_have_identical_physical_meaning() {
        for (mac, linux, windows, expected) in [
            (9, 47, 47, KeyCode::KeyV),
            (0, 30, 30, KeyCode::KeyA),
            (103, 87, 87, KeyCode::F11),
            (124, 106, 0xe04d, KeyCode::ArrowRight),
            (62, 97, 0xe01d, KeyCode::ControlRight),
        ] {
            assert_eq!(macos(mac), expected);
            assert_eq!(evdev(linux), expected);
            assert_eq!(windows_set1(windows), expected);
        }
        assert_eq!(macos(u32::MAX), KeyCode::Unidentified);
        assert_eq!(evdev(u32::MAX), KeyCode::Unidentified);
        assert_eq!(windows_set1(u32::MAX), KeyCode::Unidentified);
    }
}
